//! HermesAgent 本地调度核心模块
//!
//! 负责将用户自然语言指令路由到云端 API、本地 RPA 或混合执行通道，
//! 并在执行过程中应用三档授权策略（L1/L2/L3）与紧急停止检查。
//!
//! # 子模块
//! - [`router`]: 指令路由决策与分发
//! - [`executor`]: 路由结果的实际执行器

/// 指令路由决策模块：判断指令属于云端/本地/混合能力，并分发到对应执行器。
pub mod router;
/// 执行器模块：根据路由结果实际调用云端 API 或本地 RPA 能力完成指令。
pub mod executor;
