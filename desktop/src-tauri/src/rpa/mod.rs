//! RPA（机器人流程自动化）能力模块
//!
//! 提供四类本地操作能力，所有模块在执行前均检查紧急停止标志
//! 与授权目录白名单，确保用户可随时中断并防止越权访问。
//!
//! # 子模块
//! - [`browser`]: 浏览器自动化（打开 URL、页面数据提取）
//! - [`desktop`]: 桌面 RPA（启动应用、截图、键鼠模拟）
//! - [`file`]: 文件操作（读写、列目录、创建/删除，受授权目录限制）
//! - [`shell`]: Shell 命令执行（受三档授权策略管控）

/// 浏览器自动化模块：通过系统默认浏览器或 agent-browser CLI 打开 URL 与提取页面数据。
pub mod browser;
/// 桌面 RPA 模块：启动本地应用、屏幕截图、模拟键盘输入与鼠标点击。
pub mod desktop;
/// 文件操作模块：读写、列举、创建、删除文件，所有路径必须通过授权目录白名单校验。
pub mod file;
/// Shell 命令执行模块：执行系统命令，受三档授权策略（approve/once/free）与紧急停止管控。
pub mod shell;
